'use strict';
const assert=require('node:assert/strict');
global.window=global;
require('../assets/monsters/progression.js');
const P=global.AetheriaMonsterProgression;
assert.equal(P.MAX_LEVEL,80);
assert.equal(P.depthAt(0,0),0);
assert.equal(P.depthAt(300,0),1);
assert.equal(P.depthAt(999999,0),10);
const wolf={hp:70,dm:13,xp:15};
const start=P.levelFor(wolf,0,0,'normal',0);
const far=P.levelFor(wolf,3000,0,'normal',0);
const volcanic=P.levelFor(wolf,0,0,'normal',4);
assert.ok(volcanic>start&&volcanic>=62&&volcanic<=80);
assert.ok(start>=1&&start<=10);
assert.ok(far>start&&far<=80);
assert.equal(P.levelFor(wolf,0,0,'elite',0),Math.min(80,start+4));
assert.equal(P.levelFor(wolf,0,0,'boss',0),Math.min(80,start+12));
assert.equal(P.expMultiplier(10,10),1);
assert.equal(P.expMultiplier(18,10),.7);
assert.equal(P.expMultiplier(24,10),.4);
assert.equal(P.expMultiplier(30,10),.1);
assert.ok(P.expReward(100,10,30)<100);
const a=P.scaleStats(wolf,start),b=P.scaleStats(wolf,80);
assert.ok(b.hp>a.hp&&b.dm>=a.dm&&b.xp>a.xp);
assert.ok(P.levelFor({hp:1e9,dm:1e9},999999,999999,'boss')<=80);
console.log('PASS monster progression: area levels 1–80, tiers, and stat scaling');
