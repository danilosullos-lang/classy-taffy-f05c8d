import assert from 'node:assert/strict';
await import('../assets/engine/nav-grid.js');
const Nav=globalThis.AetheriaNavGrid;
assert.ok(Nav,'navigation module must expose the browser API');
const clear=()=>false;
assert.equal(Nav.hasClearLine({x:0,z:0},{x:10,z:0},clear),true);
const wall=(x,z)=>Math.abs(x-6)<1.05&&Math.abs(z)<5.1;
assert.equal(Nav.hasClearLine({x:0,z:0},{x:12,z:0},wall,.5),false);
const route=Nav.findPath({x:0,z:0},{x:12,z:0},wall,{cellSize:2,maxNodes:600,maxDistance:40});
assert.ok(route.length>0,'A* should route around a finite wall');
assert.ok(route.some(p=>Math.abs(p.z)>=5.5),'route should pass around the wall end');
for(const p of route)assert.equal(wall(p.x,p.z),false,'smoothed waypoint must remain outside collision');
const startInside=Nav.findPath({x:0,z:0},{x:8,z:0},(x,z)=>Math.hypot(x,z)<.2,{cellSize:2});
assert.ok(startInside.length>0,'a unit already overlapping a collider must be able to move out');
const far=Nav.findPath({x:0,z:0},{x:1000,z:0},clear,{maxDistance:20});
assert.deepEqual(far,[],'navigation range must be bounded');
const blockedAll=Nav.findPath({x:0,z:0},{x:6,z:0},()=>true,{maxNodes:100});
assert.deepEqual(blockedAll,[],'fully blocked region must return no path');
assert.deepEqual(Nav.findPath({x:0,z:0},{x:10,z:0},null),[]);
console.log('Aetheria navigation grid: line of sight, A*, wall detours and bounds passed.');
