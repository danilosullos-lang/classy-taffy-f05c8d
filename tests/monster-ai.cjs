'use strict';
const assert=require('node:assert/strict');
require('../assets/monsters/ai-state.js');
const AI=globalThis.AetheriaMonsterAI;
assert.ok(AI,'monster AI must expose a browser-compatible API');
const opts={aggroRadius:20,loseRadius:30,leashRadius:48,returnRadius:1.25,loseAggroMs:1800,attackRange:2};
const mob={d:0,z:0,homeD:0,homeZ:0,r:2};
const idle=AI.update(mob,{x:25,z:0},1000,opts);
assert.equal(idle.mode,'idle');
assert.deepEqual(idle.target,{x:0,z:0});
const chase=AI.update(mob,{x:10,z:0},1100,opts);
assert.equal(chase.mode,'chase');
assert.equal(chase.aggro,true);
const attack=AI.update(mob,{x:1,z:0},1200,opts);
assert.equal(attack.mode,'attack');
const retreat=AI.update(mob,{x:38,z:0},4000,opts);
assert.equal(retreat.mode,'return','a mob must abandon a lost target after the grace period');
assert.deepEqual(retreat.target,{x:0,z:0});
mob.d=49;
const leashed=AI.update(mob,{x:49,z:0},4100,opts);
assert.equal(leashed.mode,'return','the spawn leash must override a distant chase');
const leashPersists=AI.update(mob,{x:10,z:0},4150,opts);
assert.equal(leashPersists.mode,'return','a mob outside its leash must not reacquire before returning');
mob.d=0.5;
const home=AI.update(mob,{x:40,z:0},4200,opts);
assert.equal(home.mode,'idle','a returning mob must settle at its home point');
const reacquire=AI.update(mob,{x:8,z:0},4300,opts);
assert.equal(reacquire.mode,'chase','an idle mob must reacquire a nearby player');
mob.dead=true;
assert.equal(AI.update(mob,{x:1,z:0},4400,opts).mode,'dead');
mob.dead=false;
assert.equal(AI.reset(mob,{x:4,z:6}),true);
assert.equal(mob.aiMode,'idle');
assert.equal(mob.homeD,4);
assert.equal(mob.homeZ,6);
assert.equal(AI.update(null,{x:0,z:0},1,opts).mode,'idle');
console.log('Aetheria monster AI: aggro, attack range, target loss, leash, return, death and reset passed.');
