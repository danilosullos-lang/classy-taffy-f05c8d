'use strict';
const assert=require('node:assert/strict');
require('../assets/combat/nj-mmo-combat-core.js');
const C=globalThis.AetheriaCombatCore;
assert.ok(C,'combat core must be exported to the browser global');
assert.equal(C.calcMeleeDamage({pAtk:10},{pDef:77},{rngOffset:0}),10);
assert.equal(C.calcPhysicalSkillDamage({pAtk:10},{pDef:77},20,{rngOffset:0}),30);
assert.equal(C.calcMagicSkillDamage({mAtk:10},{mDef:91},20,{rngOffset:0}),30);
assert.equal(C.calculateAttackIntervalMs(500000),50);
assert.equal(C.isInMeleeRange(0,0,3,0,3),true);
assert.equal(C.isInMeleeRange(0,0,3.1,0,3),false);
assert.equal(C.resolveDamage({kind:'physical',attackPower:20,defense:77,critRate:0,rngOffset:0,rangeOk:false}).reason,'out_of_range');
assert.equal(C.resolveDamage({kind:'physical',attackPower:NaN,defense:77}).reason,'invalid_stats');
assert.equal(C.resolveDamage({kind:'physical',attackPower:10,defense:Infinity}).reason,'invalid_stats');
assert.equal(C.resolveDamage({kind:'physical',attackPower:10,defense:0}).reason,'invalid_stats');
assert.equal(C.resolveDamage({kind:'physical',attackPower:10,defense:77,damageMultiplier:NaN}).reason,'invalid_stats');
assert.equal(C.resolveDamage({kind:'physical',attackPower:10,defense:77,rngOffset:NaN}).reason,'invalid_stats');
const fixedVariance=C.resolveDamage({kind:'physical',attackPower:10,defense:77,randomDamage:10,rngOffset:-10,critRate:0});
assert.equal(fixedVariance.ok,true);
assert.equal(fixedVariance.damage,9);
assert.equal(C.resolveDamage({kind:'arcane',attackPower:10,defense:77}).reason,'invalid_kind');
assert.equal(C.resolveDamage({kind:'physical',attackPower:10,defense:77,rng:{nextFloat(){return 0}}}).reason,'invalid_rng');
const rng=C.createSeededRng(42);
const combat=C.createCombatState();
const target={hp:100,pDef:77,x:3,z:4};
const first=C.resolvePlayerAttack({attacker:{x:0,z:0,pAtk:10,critRate:0,attackSpeed:1000},target,state:combat,nowMs:1000,range:5,rng});
assert.equal(first.ok,true);
assert.equal(first.damage,10);
assert.equal(target.hp,90);
assert.equal(C.resolvePlayerAttack({attacker:{x:0,z:0,pAtk:10},target:{hp:100,pDef:77,x:1,z:1},nowMs:1000}).reason,'invalid_state');
const invalidTarget={hp:100,pDef:77,x:3,z:4};
const invalidAttackState=C.createCombatState();
const invalidAttack=C.resolvePlayerAttack({attacker:{x:0,z:0,pAtk:NaN,critRate:0,attackSpeed:1000},target:invalidTarget,state:invalidAttackState,nowMs:1000,range:5,rng});
assert.equal(invalidAttack.ok,false);
assert.equal(invalidAttack.reason,'invalid_stats');
assert.equal(invalidAttackState.nextAttackAtMs,0);
assert.equal(invalidTarget.hp,100);
const tooSoon=C.resolvePlayerAttack({attacker:{x:0,z:0,pAtk:10,critRate:0,attackSpeed:1000},target,state:combat,nowMs:1100,range:5,rng});
assert.equal(tooSoon.ok,false);
const castState=C.createCombatState();
assert.equal(C.beginSkillCast(castState,7,'mob-1',200,1000),true);
assert.equal(C.canUseSkill(castState,8,new Set([8]),1100),false);
assert.equal(C.completeSkillCast(castState,1199),null);
assert.deepEqual(C.completeSkillCast(castState,1200),{id:7,targetId:'mob-1'});
assert.equal(castState.castingSkillId,0);
assert.equal(C.canUseSkill(castState,8,new Set([8]),1200),true);
assert.equal(C.beginSkillCast(castState,8,'mob-2',NaN,1200),false);
assert.equal(C.beginSkillCast(castState,8,'mob-2',-1,1200),false);
assert.equal(C.beginSkillCast(castState,8,'mob-2',100,1200),true);
assert.equal(C.cancelSkillCast(castState),true);
assert.equal(C.cancelSkillCast(castState),false);
assert.equal(C.applyDamageToCastingPlayer(castState,4),false);
const state=C.createCombatState();
C.beginSkillCast(state,7,'mob-1',1200,1000);
assert.equal(C.applyDamageToCastingPlayer(state,4),true);
assert.equal(state.castingSkillId,0);
C.applyTimedEffect(target,'poison',3,5,1000);
assert.equal(target.effects.length,1);
assert.equal(C.tickTimedEffects(target,2500).length,0);
assert.equal(C.tickTimedEffects(target,4100).length,1);
assert.equal(C.canAttackPlayer({pvpFlag:0,karma:0},{pvpFlag:0,karma:0,alive:true},false),false);
assert.equal(C.canAttackPlayer({pvpFlag:0,karma:0},{pvpFlag:1,karma:0,alive:true},false),true);
assert.equal(C.canAttackPlayer({pvpFlag:0,karma:0},{pvpFlag:1,karma:0,alive:true},true),false);
const pvpResolved=C.resolvePlayerVsPlayerAttack({
  attacker:{pAtk:35,randomDamage:0,pvpFlag:1,karma:0},
  target:{pDef:77,pvpFlag:1,alive:true,hp:100},
  peaceZone:false
});
assert.equal(pvpResolved.allowed,true);
assert.equal(pvpResolved.damage,35);
assert.equal(C.resolvePlayerVsPlayerAttack({attacker:{pAtk:35},target:{pDef:77,pvpFlag:1,alive:true},rangeOk:false}).reason,'out_of_range');
assert.equal(C.resolvePlayerVsPlayerAttack({attacker:{pAtk:35},target:{pDef:77,pvpFlag:1,alive:false}}).reason,'target_unavailable');
assert.equal(C.resolvePlayerVsPlayerAttack({attacker:{pAtk:35},target:{pDef:77,pvpFlag:1,alive:true},peaceZone:true}).reason,'peace_zone');
assert.equal(C.resolvePlayerVsPlayerAttack({attacker:{pAtk:35},target:{pDef:77,pvpFlag:0,alive:true},peaceZone:false}).reason,'not_allowed');
assert.equal(C.resolvePlayerVsPlayerAttack({attacker:{pAtk:0},target:{pDef:77,pvpFlag:1,alive:true}}).reason,'invalid_stats');
assert.equal(C.resolvePlayerVsPlayerAttack({target:{pDef:77,pvpFlag:1,alive:true}}).reason,'invalid_target');
const monsterState=C.createCombatState();
const monster={x:0,z:0,damage:14,attackIntervalMs:1300};
const player={x:3,z:4,hp:100,alive:true};
const monsterHit=C.resolveMonsterAttack({attacker:monster,target:player,state:monsterState,nowMs:1000,range:5});
assert.equal(monsterHit.ok,true);
assert.equal(monsterHit.damage,14);
assert.equal(monsterHit.nextAttackAtMs,2300);
assert.equal(C.resolveMonsterAttack({attacker:monster,target:player,state:monsterState,nowMs:2299,range:5}).reason,'cooldown');
assert.equal(C.resolveMonsterAttack({attacker:monster,target:player,state:monsterState,nowMs:2300,range:4.9}).reason,'out_of_range');
assert.equal(C.resolveMonsterAttack({attacker:monster,target:{...player,hp:0},state:monsterState,nowMs:4000,range:5}).reason,'not_attackable');
assert.equal(C.resolveMonsterAttack({attacker:monster,target:player,state:monsterState,nowMs:4000,range:5,peaceZone:true}).reason,'not_attackable');
assert.equal(C.resolveMonsterAttack({attacker:monster,target:player,state:monsterState,nowMs:4000,range:5}).ok,true);
console.log('Aetheria combat core: player, monster, cooldown, range, cast interruption, effects and PvP rules passed.');
